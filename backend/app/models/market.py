def _in(column: str, values: tuple[str, ...]) -> str:
    return f"{column} IN ({', '.join(repr(v) for v in values)})"


order_number_seq = Sequence("order_number_seq", start=100001, metadata=Base.metadata)


# ── Virtual property ────────────────────────────────────────────────────────────────


class VirtualProperty(UUIDPrimaryKey, CreatedAtMixin, Base):
    """A claimable virtual shop unit: a ground-floor frontage of a real (non-residential)
    OSM building, facing a real street. Generated by `app.marketplace.units`."""

    __tablename__ = "virtual_properties"
    __table_args__ = (
        CheckConstraint("kind = 'shop_unit'", name="kind_valid"),
        CheckConstraint("width_m > 0 AND depth_m > 0 AND ceiling_m > 0", name="size_positive"),
        Index("ix_virtual_properties_footprint", "footprint", postgresql_using="gist"),
        Index("ix_virtual_properties_door", "door", postgresql_using="gist"),
        Index("ix_virtual_properties_building", "building_id"),
    )

    code: Mapped[str] = mapped_column(String(16), unique=True)  # "DP-0412", shown to people
    unit_key: Mapped[str] = mapped_column(String(64), unique=True)  # stable across re-imports
    region_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("geographic_regions.id", ondelete="CASCADE")
    )
    building_id: Mapped[int | None] = mapped_column(ForeignKey("buildings.id", ondelete="SET NULL"))
    kind: Mapped[str] = mapped_column(String(16), default="shop_unit", server_default="shop_unit")
    street_name: Mapped[str | None] = mapped_column(String(200))
    street_name_km: Mapped[str | None] = mapped_column(String(200))
    # World geometry (UTM metres, x east, z = -north): door = centre of the street frontage.
    door_x: Mapped[float] = mapped_column(Float)
    door_z: Mapped[float] = mapped_column(Float)
    heading: Mapped[float] = mapped_column(Float)  # yaw pointing out of the door to the street
    width_m: Mapped[float] = mapped_column(Float)
    depth_m: Mapped[float] = mapped_column(Float)
    ceiling_m: Mapped[float] = mapped_column(Float)
    corners: Mapped[list[list[float]]] = mapped_column(JSONB)  # 4 world [x, z], door edge first
    footprint: Mapped[Any] = mapped_column(Geometry("POLYGON", srid=4326, spatial_index=False))
    door: Mapped[Any] = mapped_column(Geometry("POINT", srid=4326, spatial_index=False))
    # A named real business (OSM shop/amenity/office...) occupies this building: claiming needs
    # evidence and an administrator's review, and the real owner can dispute.
    requires_verification: Mapped[bool] = mapped_column(Boolean, default=False)
    real_business_name: Mapped[str | None] = mapped_column(String(200))
    is_active: Mapped[bool] = mapped_column(Boolean, default=True, server_default="true")


