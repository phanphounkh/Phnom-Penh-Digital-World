class Order(UUIDPrimaryKey, TimestampMixin, Base):
    __tablename__ = "orders"
    __table_args__ = (
        CheckConstraint(_in("status", ORDER_STATUSES), name="status_valid"),
        CheckConstraint(_in("fulfillment", FULFILLMENT), name="fulfillment_valid"),
        CheckConstraint(
            "subtotal_minor >= 0 AND delivery_fee_minor >= 0 "
            "AND total_minor = subtotal_minor + delivery_fee_minor",
            name="totals_consistent",
        ),
        CheckConstraint("currency = 'USD'", name="currency_usd"),
        Index("ix_orders_buyer_created", "buyer_id", "created_at"),
        Index("ix_orders_merchant_status", "merchant_id", "status"),
    )

    number: Mapped[str] = mapped_column(
        String(20),
        unique=True,
        server_default=text("'PP-' || nextval('order_number_seq'::regclass)"),
    )
    buyer_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))
    merchant_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("merchants.id", ondelete="RESTRICT"))
    pickup_shop_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("shops.id", ondelete="SET NULL")
    )
    payment_intent_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("payment_intents.id", ondelete="RESTRICT"), index=True
    )
    status: Mapped[str] = mapped_column(String(24))
    fulfillment: Mapped[str] = mapped_column(String(16), default="pickup")
    subtotal_minor: Mapped[int] = mapped_column(Integer)
    delivery_fee_minor: Mapped[int] = mapped_column(Integer, default=0, server_default="0")
    total_minor: Mapped[int] = mapped_column(Integer)
    currency: Mapped[str] = mapped_column(String(3), default="USD", server_default="USD")
    note: Mapped[str | None] = mapped_column(String(300))
    cancel_reason: Mapped[str | None] = mapped_column(String(300))
    paid_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    completed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    items: Mapped[list["OrderItem"]] = relationship(
        lazy="selectin", cascade="all, delete-orphan", order_by="OrderItem.id"
    )
    events: Mapped[list["OrderEvent"]] = relationship(
        lazy="selectin", cascade="all, delete-orphan", order_by="OrderEvent.id"
    )
    merchant: Mapped[Merchant] = relationship(lazy="joined")
    payment_intent: Mapped[PaymentIntent] = relationship(back_populates="orders")


