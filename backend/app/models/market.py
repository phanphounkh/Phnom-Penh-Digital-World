class Shop(UUIDPrimaryKey, TimestampMixin, Base):
    """A merchant's storefront in the 3D city, on one claimed unit. It shows the merchant's
    catalogue (several units of one merchant are branches with the same products)."""

    __tablename__ = "shops"
    __table_args__ = (
        CheckConstraint("status IN ('active','ended')", name="status_valid"),
        CheckConstraint(_in("theme", SHOP_THEMES), name="theme_valid"),
        CheckConstraint("primary_color ~ '^#[0-9a-f]{6}$'", name="primary_color_hex"),
        CheckConstraint("accent_color ~ '^#[0-9a-f]{6}$'", name="accent_color_hex"),
        Index(
            "uq_shops_property_active",
            "property_id",
            unique=True,
            postgresql_where=text("status = 'active'"),
        ),
        Index("ix_shops_merchant", "merchant_id"),
    )

    merchant_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("merchants.id", ondelete="CASCADE"))
    property_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("virtual_properties.id", ondelete="CASCADE")
    )
    claim_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("property_claims.id", ondelete="CASCADE"), unique=True
    )
    name: Mapped[str] = mapped_column(String(60))
    name_km: Mapped[str | None] = mapped_column(String(60))
    tagline: Mapped[str | None] = mapped_column(String(80))
    theme: Mapped[str] = mapped_column(String(16), default="market", server_default="market")
    primary_color: Mapped[str] = mapped_column(String(7), default="#c4552f")
    accent_color: Mapped[str] = mapped_column(String(7), default="#e8a33d")
