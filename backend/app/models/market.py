    __tablename__ = "merchants"
    __table_args__ = (
        CheckConstraint(_in("status", MERCHANT_STATUSES), name="status_valid"),
        CheckConstraint(_in("category", BUSINESS_CATEGORIES), name="category_valid"),
        Index("ix_merchants_status", "status"),
    )

    owner_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"), unique=True
    )
