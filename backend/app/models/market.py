"""Marketplace data (Phase 4): virtual shop units and claims, merchants, shops, catalogue,
carts, orders and the demo checkout.

Rules that live in the database, not only in code:
* a virtual unit has at most one live (pending or approved) claim: partial unique index;
* a unit hosts at most one active shop: partial unique index;
* money is integer minor units (US cents) with CHECK constraints, never floats;
* a payment intent is unique per (buyer, idempotency key), and an order is refunded at most
  once (unique refund per order).

Virtual units are storefronts in the 3D city. A claim never grants any right to real property,
and units in residential buildings are never generated.
"""

